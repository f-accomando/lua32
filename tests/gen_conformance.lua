        "LDA #0xCDAB\nSTA 0xFFFFFF\nLDA #0\nLDA 0xFFFFFF\nSTA 0x0330\nLDX #2\nLDA 0xFFFFFF,X\nSTA 0x0332",
        "IN\nSTA 0x0340\nLDA 0x0AC800\nSTA 0x0342\nLDX 0x0AC7FF\nSTX 0x0344\nLDA #0\nOR 0x0AC800\nAND #0x10",
        "LDX #500\nCLAMPX 10,300\nLDY #5\nCLAMPY 10,300\nSTX 0x0350\nSTY 0x0352\nLDX #0xFFFF\nCLAMPX 0,0x8000",
        "LDA #1\nSTA 0x0AC801\nLDA 0x0AC801\nSTA 0x0360\nLDA #9\nSTA 0x0AC801",
        "LDA #13\nSTA 0x0AC802\nLDA #0x0107\nSTA 0x0AC803\nLDA 0x0AC802\nSTA 0x0362",
        "LDA #0\nSTA 0x0AC801\nLDA #1\nSTA 0x0AC805\nLDA #0x03FF\nSTA 0x0AC802",
        "LDA #0x00FF\nSTA 0x0AB003\nLDA #0x2040\nSTA 0x0AB005",           -- CGRAM via CPU
        "",                                                              -- flag persistenti
        "LDX #50000\nloop1:\nDEX\nJNZ loop1",                          -- ~100k istruzioni
        "LDA #0x5A5A\nSTA 0x0AC900\nSTA 0x0AC97E\nLDA #0x0101\nSTA 0x0AC808",
