-- -----------------------------------------------------------
-- 3. PPU: scroll, stage, banchi grafici, sprite
-- -----------------------------------------------------------
do
    local OAM = mm.OAM_BASE
    local init = {}
    local function slot(n, x, y, tile, pal, attr)
        local base = OAM + n * 8
        init[#init + 1] = string.format("LDA #%d\nSTA %d", x % 65536, base)
        init[#init + 1] = string.format("LDA #%d\nSTA %d", y % 65536, base + 2)
        init[#init + 1] = string.format("LDA #%d\nSTA %d", ppu.encode_tile_descriptor(tile, pal), base + 4)
        init[#init + 1] = string.format("LDA #%d\nSTA %d", attr, base + 6)
    end
    slot(0, 20, 30, 2, 1, 1)
    slot(1, 28, 38, 3, 2, 1)            -- sopra lo slot 0
    slot(2, -8, 50, 4, 3, 1)            -- x negativa
    slot(3, 300, 200, 4, 4, 1)          -- esce a destra e in basso
    slot(4, 100, -20, 3, 5, 1 + 2)      -- flip x, y negativa
    slot(5, 140, 100, 5, 6, 1)          -- freccia normale
    slot(6, 150, 100, 5, 6, 1 + 2)      -- flip x
    slot(7, 160, 100, 5, 6, 1 + 4)      -- flip y
    slot(8, 170, 100, 5, 6, 1 + 2 + 4)  -- flip x+y
    slot(9, 200, 60, 0, 7, 1)           -- tile 0: disegnato (sprite)
    slot(10, 60, 60, 2, 0, 0)           -- invisibile
    slot(511, 24, 34, 1, 7, 1)          -- ultimo slot: sopra a tutti
    slot(12, -100, -100, 4, 0, 1)       -- completamente fuori schermo

    local SX, SY, INIT = 0x0400, 0x0402, 0x0404
    local src = table.concat({
        "LDA " .. INIT, "JNZ ready", table.concat(init, "\n"), "LDA #1", "STA " .. INIT,
        "ready:",
        -- scroll: +5 / +3 per tick
        "LDA " .. SX, "ADD #5", "STA " .. SX, "STA 0x0AC802",
        "LDA " .. SY, "ADD #3", "STA " .. SY, "STA 0x0AC803",
        -- sprite 0 si muove a destra
        "LDA " .. OAM, "ADD #2", "STA " .. OAM,
        -- eventi a tick fissi (contatore)
        "LDA " .. COUNTER, "INC " .. COUNTER,
        "CMP #20", "JNZ e1", "LDA #1", "STA 0x0AC801", "e1:",
        "LDA " .. (COUNTER), "CMP #31", "JNZ e2", "LDA #1", "STA 0x0AC805", "e2:",
        "LDA " .. COUNTER, "CMP #41", "JNZ e3", "LDA #0", "STA " .. (OAM + 6), "e3:",
        "LDA " .. COUNTER, "CMP #51", "JNZ e4", "LDA #0xFFF0", "STA " .. SX, "STA 0x0AC802", "e4:",
        "LDA " .. COUNTER, "CMP #56", "JNZ e5", "LDA #0", "STA 0x0AC801", "e5:",
        "HALT",
    }, "\n")
    local path = pack("ppu", src, { [0] = stage0, [1] = stage1 }, { [0] = gfx0, [1] = gfx1 }, cgram)
    local inputs = {}
    for i = 1, 64 do inputs[i] = 0 end
    run_vectors("ppu", path, inputs)
end

-- -----------------------------------------------------------
-- 4. crash: ogni caso termina con una riga "crash"
-- -----------------------------------------------------------
local function crash_case(name, body)
    -- due tick normali, poi il blocco che deve andare in crash
    local src = dispatcher({ "LDA #1", "LDA #2", body })
    local path = pack(name, src)
    run_vectors(name, path, { 0, 0, 0, 0 })
end
crash_case("crash_opcode", "LDA #0x00FF\nSTA 0x0400\nJMP 0x0400")        -- opcode 0xFF
crash_case("crash_underflow", "RTS")
-- il ciclo di push sta nella RAM libera (0x0B0000), non nella WRAM, cosi'
-- lo stack non lo sovrascrive: PHA; JMP 0x0B0000 = 70 60 00 00 0B
crash_case("crash_overflow",
    "LDA #0x6070\nSTA 0x0B0000\nLDA #0\nSTA 0x0B0002\nLDA #0x000B\nSTA 0x0B0004\nJMP 0x0B0000")
crash_case("crash_limit", "loop3:\nJMP loop3")

-- non e' un crash: lo stack scende fino a sovrascrivere il codice stesso
-- (a 0x1000), che diventa "RTS HALT" - deterministico, utile come test di
-- automodifica
do
    local path = pack("stack_smash", dispatcher({ "LDA #1", "LDA #2", "LDA #0x0168\nloop2:\nPHA\nJMP loop2" }))
    run_vectors("stack_smash", path, { 0, 0, 0, 0 })
end

