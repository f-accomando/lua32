        {0x05, 60}, {0x0A, 200}, {0x00, 2}, {0x09, 10}, {0x16, 10},
    }))
end

-- -----------------------------------------------------------
-- 2. CPU: un blocco di test per tick
-- -----------------------------------------------------------
do
    local R = 0x0200  -- area risultati in WRAM
    local blocks = {
        "LDA #0",                                                       -- Z
        "LDA #0x8000",                                                  -- N
        "LDA #0xFFFF\nADD #1",                                          -- C Z
        "LDA #0x7FFF\nADD #1",                                          -- V N
        "LDA #0x8000\nADD #0x8000",                                     -- C V Z
        "LDA #5\nSUB #7",                                               -- borrow
        "LDA #0x8000\nSUB #1",                                          -- V
        "LDA #7\nSUB #7",                                               -- Z C
        "LDA #0x0F0F\nAND #0x00FF\nSTA 0x0200\nOR #0xF000\nSTA 0x0202\nXOR #0xFFFF\nSTA 0x0204",
        "LDA #3\nCMP #3\nCMP #4",
        "LDA #9\nCMP #2\nCMP #0x8000",
        "LDA #0x8001\nASL\nSTA 0x0206\nLSR\nLSR",
        "LDA #0xFFFF\nSTA 0x0208\nINC 0x0208\nDEC 0x0208\nDEC 0x0208",
        "LDX #0\nDEX\nINY\nINY\nTXA\nTAY\nDEY\nTYX\nINX\nTXY",
        "LDA #0x1234\nPHA\nLDA #0\nPLA\nLDX #0x1111\nLDY #0x2222\nPHX\nPHY\nPLX\nPLY",
        "JSR sub1\nSTA 0x020A\nJMP after1\nsub1:\nLDA #0x4242\nJSR sub2\nRTS\nsub2:\nADD #1\nRTS\nafter1:",
        "LDX #4\nLDY #6\nLDA #0xAAAA\nSTA 0x0300,X\nLDA #0xBBBB\nSTA 0x0300,Y\nLDA 0x0300,X\nADD 0x0300,Y\nSTA 0x0310\nINC 0x0300,X\nDEC 0x0300,Y\nLDA #0xAAAB\nCMP 0x0300,X",
