--[[
gen_conformance.lua - genera i vettori di conformita' della specifica s32
(docs/spec/s32-spec.md, sezione 9) usando i moduli di riferimento di lua32
(cpu.lua, ppu.lua, cart.lua, assembler.lua) - niente SDL, gira anche
headless:

    luajit tests/gen_conformance.lua

Scrive in docs/spec/conformance/ una cartuccia .cart e un file .vec per
ogni caso. Ogni riga del .vec e' un tick:

    <tick> <input> <crc WRAM> <crc VRAM..APU> <crc frame RGB> <A> <X> <Y> <FLAGS> <SP>

oppure "<tick> <input> crash". Un'altra implementazione (es. bm33) e'
conforme se riproduce tutte le righe. Le cartucce sono deterministiche
(uid a zero, data 0): rigenerare deve dare file identici.
]]
local script_dir = arg[0]:match("(.*/)") or "./"
package.path = script_dir .. "../?.lua;" .. package.path

local ffi = require("ffi")
local bit = require("bit")
local mm = require("memory_map")
local cpu_mod = require("cpu")
local ppu = require("ppu")
local cart = require("cart")
local asm = require("assembler")

local OUT = script_dir .. "../docs/spec/conformance/"
local W, H = 320, 224
local LOAD = 0x1000
local HW_BASE, HW_END = mm.VRAM_BASE, mm.APU_END

-- -----------------------------------------------------------
-- CRC32 su memoria FFI (stesso polinomio di cart.lua / zlib)
-- -----------------------------------------------------------
local crc_tab = ffi.new("uint32_t[256]")
for i = 0, 255 do
    local c = i
    for _ = 1, 8 do
        if bit.band(c, 1) ~= 0 then c = bit.bxor(0xEDB88320, bit.rshift(c, 1)) else c = bit.rshift(c, 1) end
    end
    crc_tab[i] = c
end
local function crc(ptr, n)
    local c = 0xFFFFFFFF
    for i = 0, n - 1 do
        c = bit.bxor(crc_tab[bit.band(bit.bxor(c, ptr[i]), 0xFF)], bit.rshift(c, 8))
    end
    return bit.tohex(bit.bnot(c))
end

-- -----------------------------------------------------------
-- helper: bytes, cartucce, esecuzione
-- -----------------------------------------------------------
local function bytes_to_string(t)
    local parts = {}
    for i = 1, #t do parts[i] = string.char(t[i]) end
    return table.concat(parts)
end

local function pack(name, src, stages, gfx, cgram)
    local code = bytes_to_string(asm.assemble(src, LOAD))
    cart.pack({
        meta = { uid = string.rep("\0", 16), title = "conformance: " .. name,
                 author = "s32 spec v0.1", created = 0 },
        code = code, stage_banks = stages or {}, gfx_banks = gfx or {}, cgram = cgram,
    }, OUT .. name .. ".cart")
    return OUT .. name .. ".cart"
end

local function run_vectors(name, cart_path, inputs)
    local loaded = cart.load(cart_path)
    local cpu = cpu_mod.new()
    cart.install(cpu, loaded, LOAD)
    local lines = {
        "# s32 conformance vectors, spec v0.1 - generated by tests/gen_conformance.lua",
        "# cart=" .. cart_path:match("[^/]+$") .. " ticks=" .. #inputs,
        "# tick input crc_wram crc_hw crc_frame A X Y FLAGS SP",
    }
    for t = 1, #inputs do
        local ib = inputs[t]
        local ok = pcall(cpu.run, cpu, LOAD, ib)
        if not ok then
            lines[#lines + 1] = string.format("%d %02x crash", t - 1, ib)
            break
        end
        local frame = ppu.render_frame(cpu.mem, cpu.scroll_x, cpu.scroll_y, W, H)
        lines[#lines + 1] = string.format("%d %02x %s %s %s %04x %04x %04x %02x %06x",
            t - 1, ib, crc(cpu.mem, mm.WRAM_END), crc(cpu.mem + HW_BASE, HW_END - HW_BASE),
            crc(frame, W * H * 3), cpu.a, cpu.x, cpu.y, cpu.flags, cpu.sp)
    end
    local f = assert(io.open(OUT .. name .. ".vec", "w"))
    f:write(table.concat(lines, "\n"), "\n")
    f:close()
    print(string.format("%-16s %4d tick -> %s.vec", name, #lines - 3, name))
end

-- sequenza di input deterministica: segmenti {byte, ripetizioni}
local function input_script(segments)
    local out = {}
    for _, s in ipairs(segments) do
        for _ = 1, s[2] do out[#out + 1] = s[1] end
    end
    return out
end

-- dispatcher: un blocco di test per tick, scelto da un contatore in WRAM
local COUNTER = 0x0100
local function dispatcher(blocks)
    local src = { "LDA " .. COUNTER, "INC " .. COUNTER }
    for i = 1, #blocks do
        src[#src + 1] = string.format("CMP #%d", i - 1)
        src[#src + 1] = string.format("JZ t%d", i - 1)
    end
    src[#src + 1] = "HALT"
    for i, b in ipairs(blocks) do
        src[#src + 1] = string.format("t%d:", i - 1)
        src[#src + 1] = b
        src[#src + 1] = "HALT"
    end
    return table.concat(src, "\n")
end

-- -----------------------------------------------------------
-- grafica di test (banchi, palette, stage)
-- -----------------------------------------------------------
local GFX_BANK_SIZE = mm.DIRECTORY_BYTES + mm.GRAPHICS_POOL_BYTES
local TILES = {  -- indice tile -> {offset nell'archivio, classe di taglia}
    [1] = {0, 0},     -- 8x8
    [5] = {64, 0},    -- 8x8 asimmetrico (freccia) per i flip
    [2] = {128, 1},   -- 16x16
    [3] = {384, 2},   -- 32x32
    [4] = {1408, 3},  -- 64x64
}

local function make_gfx_bank(variant)
    local b = ffi.new("uint8_t[?]", GFX_BANK_SIZE)
    for idx, t in pairs(TILES) do
        local d = idx * mm.DIRECTORY_ENTRY_BYTES
        b[d], b[d + 1], b[d + 2], b[d + 3] = t[1] % 256, math.floor(t[1] / 256) % 256, math.floor(t[1] / 65536), t[2]
    end
    local pool = mm.DIRECTORY_BYTES
    local function px(offset, size, x, y, v) b[pool + offset + y * size + x] = v end
    for y = 0, 7 do for x = 0, 7 do  -- tile 1: scacchiera con buchi trasparenti
        px(0, 8, x, y, ((x + y) % 3 == 0) and 0 or ((x * 3 + y + variant) % 7 + 1))
    end end
    for y = 0, 7 do for x = 0, 7 do  -- tile 5: freccia verso destra/in alto
        px(64, 8, x, y, (x >= y and y < 4) and (10 + x + variant) or 0)
    end end
    for y = 0, 15 do for x = 0, 15 do  -- tile 2: gradiente pieno
        px(128, 16, x, y, (x * 16 + y + variant * 3) % 255 + 1)
    end end
    for y = 0, 31 do for x = 0, 31 do  -- tile 3: cerchio, trasparente fuori
        local dx, dy = 2 * x - 31, 2 * y - 31
        px(384, 32, x, y, (dx * dx + dy * dy <= 31 * 31) and ((x + 2 * y + variant) % 200 + 20) or 0)
    end end
    for y = 0, 63 do for x = 0, 63 do  -- tile 4: strisce diagonali con buchi
        px(1408, 64, x, y, ((x + y) % 8 < 5) and ((x + y + variant * 5) % 100 + 100) or 0)
    end end
    return ffi.string(b, GFX_BANK_SIZE)
end

local function make_cgram()
    local c = ffi.new("uint8_t[?]", mm.CGRAM_SIZE)
    for p = 0, 7 do for i = 0, 255 do
        local a = (p * 256 + i) * 3
        c[a], c[a + 1], c[a + 2] = (i * 7 + p * 31) % 256, (i * 13 + p * 17) % 256, (i * 29 + p * 5) % 256
    end end
    return ffi.string(c, mm.CGRAM_SIZE)
end

local function make_stage(pattern)
    local s = ffi.new("uint8_t[?]", mm.TILEMAP_BYTES)
    for cy = 0, mm.TILEMAP_H - 1 do for cx = 0, mm.TILEMAP_W - 1 do
        local tile, pal = pattern(cx, cy)
        local w = ppu.encode_tile_descriptor(tile, pal)
        local a = (cy * mm.TILEMAP_W + cx) * 2
        s[a], s[a + 1] = w % 256, math.floor(w / 256)
    end end
    return ffi.string(s, mm.TILEMAP_BYTES)
end

-- stage 0: tutte le taglie mescolate, con sovrapposizioni e celle vuote
local stage0 = make_stage(function(cx, cy)
    local k = (cx * 7 + cy * 3) % 11
    local tile = ({0, 1, 1, 5, 2, 1, 3, 0, 1, 4, 2})[k + 1]
    return tile, (cx + 2 * cy) % 8
end)
-- stage 1: pochi tile grandi sparsi su fondo vuoto
local stage1 = make_stage(function(cx, cy)
    if cx % 9 == 0 and cy % 7 == 0 then return 4, (cx + cy) % 8 end
    if cx % 5 == 2 and cy % 4 == 1 then return 3, cy % 8 end
    if (cx + cy) % 13 == 0 then return 1, 3 end
    return 0, 0
end)

local gfx0, gfx1, cgram = make_gfx_bank(0), make_gfx_bank(1), make_cgram()

